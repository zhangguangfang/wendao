#!/usr/bin/env node

import { mkdir, readFile, readdir, realpath, rm, stat, writeFile, chmod } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { zipSync } from "fflate";
import { createHash } from "node:crypto";

const project = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const release = join(project, "release");
const destination = join(release, "缓缓");
const marker = ".huanhuan-generated";

async function exists(path) {
  try { await stat(path); return true; }
  catch (error) { if (error.code === "ENOENT") return false; throw error; }
}

if (await exists(destination)) {
  if (!(await exists(join(destination, marker)))) {
    throw new Error("release/缓缓 已存在且不是本脚本生成的目录，请先将已有文件移到安全位置。");
  }
  await rm(destination, { recursive: true });
}
await mkdir(destination, { recursive: true });
await writeFile(join(destination, marker), "Generated by scripts/package-local.mjs\n");

const portableSources = [
  ".gitignore", ".github", "README.md", "本地使用说明.md", "先读我.txt", "验收与审查报告.md", "ITERATION_LOG.md", "ITERATION_V030.md", "ITERATION_V040.md",
  "打开缓缓.bat", "打开缓缓.command", "打开缓缓.sh", "更新缓缓.bat",
  "index.html", "package.json", "package-lock.json", "tsconfig.json",
  "vite.config.ts", "playwright.config.ts", "src", "public", "scripts", "tests", "dist",
];

async function copy(source, target) {
  const info = await stat(source);
  const actual = await realpath(source);
  if (actual !== source || !actual.startsWith(project + sep)) throw new Error(`不能打包链接或项目外的文件：${source}`);
  if (info.isDirectory()) {
    await mkdir(target, { recursive: true });
    for (const entry of await readdir(source, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) throw new Error(`不能打包符号链接：${entry.name}`);
      await copy(join(source, entry.name), join(target, entry.name));
    }
  } else if (info.isFile()) {
    let contents = await readFile(source);
    if (source.endsWith(".bat")) contents = Buffer.from(contents.toString("utf8").replace(/\r?\n/g, "\r\n"));
    // Windows PowerShell 5.1 needs a BOM to reliably read Chinese string literals.
    if (source.endsWith(".ps1")) contents = Buffer.from("\ufeff" + contents.toString("utf8").replace(/^\ufeff/, "").replace(/\r?\n/g, "\r\n"));
    await writeFile(target, contents);
    await chmod(target, /\.(?:command|sh)$/.test(source) ? 0o755 : 0o644);
  }
}
for (const entry of portableSources) await copy(join(project, entry), join(destination, entry));

let html = await readFile(join(project, "dist/index.html"), "utf8");
const distRoot = await realpath(join(project, "dist"));
async function asset(url) {
  const path = await realpath(resolve(distRoot, url.replace(/^\//, "")));
  if (!path.startsWith(distRoot + sep)) throw new Error("构建资源超出 dist 目录。");
  return readFile(path, "utf8");
}

const scriptPattern = /<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/g;
const scripts = [...html.matchAll(scriptPattern)];
if (scripts.length !== 1) throw new Error("需要单个完整的生产脚本，无法生成离线页面。");
if (/<link\b[^>]*rel=["']modulepreload["']/i.test(html)) {
  throw new Error("构建包含额外的 JavaScript 模块，不能生成完整离线页面。");
}
for (const match of scripts) {
  const javascript = await asset(match[1]);
  if (/\bimport\s*\(/.test(javascript)) throw new Error("构建包含动态导入，不能生成完整离线页面。");
  html = html.replace(match[0], () => `<script type="module">\n${javascript.replace(/<\/script/gi, "<\\/script")}\n</script>`);
}
const styles = [...html.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g)];
if (!styles.length) throw new Error("未找到生产样式文件。");
for (const match of styles) {
  const css = await asset(match[1]);
  if (/url\(\s*["']?(?!data:|#)[^\s)]/i.test(css)) throw new Error("样式依赖外部资源，不能生成完整离线页面。");
  html = html.replace(match[0], () => `<style>\n${css.replace(/<\/style/gi, "<\\/style")}\n</style>`);
}
const favicon = (await readFile(join(project, "public/favicon.svg"))).toString("base64");
html = html.replace(/href="\/favicon\.svg"/, `href="data:image/svg+xml;base64,${favicon}"`);
html = html.replace("</body>", '<noscript>请在浏览器中启用 JavaScript 以使用缓缓。</noscript>\n</body>');
await writeFile(join(destination, "打开缓缓.html"), html, "utf8");

const archive = {};
async function addToArchive(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await addToArchive(path);
    else {
      const filename = `缓缓/${relative(destination, path).split(sep).join("/")}`;
      const executable = /\.(?:command|sh)$/.test(entry.name);
      archive[filename] = [new Uint8Array(await readFile(path)), { os: 3, attrs: (executable ? 0o100755 : 0o100644) * 65536 }];
    }
  }
}
await addToArchive(destination);
const zipped = zipSync(archive, { level: 6 });
const output = join(release, "缓缓.zip");
await writeFile(output, zipped);
const { version } = JSON.parse(await readFile(join(project, "package.json"), "utf8"));
await writeFile(join(release, "update.json"), JSON.stringify({
  app: "huanhuan", format: 1, version, bytes: zipped.byteLength,
  sha256: createHash("sha256").update(zipped).digest("hex"),
}, null, 2) + "\n");
console.log(`本地项目文件夹：${destination}`);
console.log(`可下载压缩包：${output}（${Math.round(zipped.byteLength / 1024)} KB）`);
console.log("解压后，双击“缓缓/打开缓缓.html”即可预览，无需安装依赖。");
